import type { Metadata, Viewport } from 'next'
import { Inter, Sora } from 'next/font/google'

import './globals.css'

import { ScrollToTop } from '@/components/ScrollToTop'
import { serializeJsonLd, websiteSchema } from '@/lib/seo'
import { SITE, canonicalOrigin, isProductionSite } from '@/lib/site'

/*
 * Fonts are self-hosted at build time by `next/font` (no third-party request,
 * no FOUC, and `display: swap` plus metric-aware fallback keeps CLS at 0).
 */
const inter = Inter({
  subsets: ['latin'],
  display: 'swap',
  variable: '--font-inter',
  adjustFontFallback: true,
  fallback: [
    'ui-sans-serif',
    'system-ui',
    '-apple-system',
    'Segoe UI',
    'Roboto',
    'Helvetica Neue',
    'Arial',
    'Noto Sans',
    'sans-serif'
  ]
})

const sora = Sora({
  subsets: ['latin'],
  display: 'swap',
  variable: '--font-sora',
  fallback: ['ui-sans-serif', 'system-ui', 'Segoe UI', 'Roboto', 'Arial', 'sans-serif']
})

